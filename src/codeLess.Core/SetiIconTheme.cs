        public static SetiIconInfo Resolve(string fileNameOrExt, bool isLight = false, string languageId = null)
        {
            EnsureInitialized();
            string raw = (fileNameOrExt ?? "").Trim();
            string fn = raw;
            int slash = Math.Max(fn.LastIndexOf('/'), fn.LastIndexOf('\\'));
            if (slash >= 0) fn = fn.Substring(slash + 1);
            string fnLow = fn.ToLowerInvariant();

            string iconId = null;
            if (fnLow.Length > 0)
            {
                if (isLight && lightFileNames.TryGetValue(fnLow, out iconId)) { }
                else if (darkFileNames.TryGetValue(fnLow, out iconId)) { }
            }

            if (iconId == null && fnLow.Length > 0)
            {
                int dot = fnLow.IndexOf('.');
                while (dot >= 0 && dot + 1 < fnLow.Length)
                {
                    string ext = fnLow.Substring(dot + 1);
                    if (isLight && lightFileExtensions.TryGetValue(ext, out iconId)) break;
                    if (darkFileExtensions.TryGetValue(ext, out iconId)) break;
                    dot = fnLow.IndexOf('.', dot + 1);
                }
            }

            if (iconId == null)
            {
                string lid = !string.IsNullOrEmpty(languageId) ? languageId.Trim().ToLowerInvariant() : ResolveLanguageId(fnLow);
                if (!string.IsNullOrEmpty(lid))
                {
                    if (isLight && lightLanguageIds.TryGetValue(lid, out iconId)) { }
                    else if (darkLanguageIds.TryGetValue(lid, out iconId)) { }
                }
            }

            if (iconId == null && fnLow.Length > 0 && fnLow.IndexOf('.') < 0)
            {
                if (isLight && lightFileExtensions.TryGetValue(fnLow, out iconId)) { }
                else if (darkFileExtensions.TryGetValue(fnLow, out iconId)) { }
                else
                {
                    string lid2;
                    if (extToLanguageId.TryGetValue(fnLow, out lid2))
                    {
                        if (isLight && lightLanguageIds.TryGetValue(lid2, out iconId)) { }
                        else darkLanguageIds.TryGetValue(lid2, out iconId);
                    }
                    else if (isLight && lightLanguageIds.TryGetValue(fnLow, out iconId)) { }
                    else darkLanguageIds.TryGetValue(fnLow, out iconId);
                }
            }

            if (iconId == null) iconId = isLight ? DefaultLightIconId : DefaultDarkIconId;
            SetiIconInfo info;
            if (definitions.TryGetValue(iconId, out info)) return info;
            return definitions[isLight ? DefaultLightIconId : DefaultDarkIconId];
        }

        public static SetiIconInfo GetIcon(string fileNameOrExt, bool isLight = false, string languageId = null)
        {
            return Resolve(fileNameOrExt, isLight, languageId);
        }

        public static SetiIconInfo GetForFile(string fileNameOrPath, StudioTheme theme = null, string languageId = null)
        {
            return Resolve(fileNameOrPath, theme != null && theme.IsLight, languageId);
        }

        public static SetiIconInfo GetForLanguage(string languageId, bool isLight = false)
        {
            EnsureInitialized();
            string lid = (languageId ?? "").Trim().TrimStart('.').ToLowerInvariant();
            string iconId = null;
            if (lid.Length > 0)
            {
                if (isLight && lightLanguageIds.TryGetValue(lid, out iconId)) { }
                else if (darkLanguageIds.TryGetValue(lid, out iconId)) { }
                else
                {
                    string mapped;
                    if (extToLanguageId.TryGetValue(lid, out mapped))
                    {
                        if (isLight && lightLanguageIds.TryGetValue(mapped, out iconId)) { }
                        else darkLanguageIds.TryGetValue(mapped, out iconId);
                    }
                }
            }
            if (iconId == null) iconId = isLight ? DefaultLightIconId : DefaultDarkIconId;
            SetiIconInfo info;
            if (definitions.TryGetValue(iconId, out info)) return info;
            return definitions[isLight ? DefaultLightIconId : DefaultDarkIconId];
        }

        public static void GetFileIcon(string fileNameOrPath, bool isLight, out string glyph, out Color color)
        {
            SetiIconInfo info = Resolve(fileNameOrPath, isLight, null);
            glyph = info.Glyph;
            color = info.Color;
        }

        public static void GetFileIcon(string fileNameOrPath, StudioTheme theme, out string glyph, out Color color)
        {
            SetiIconInfo info = Resolve(fileNameOrPath, theme != null && theme.IsLight, null);
            glyph = info.Glyph;
            color = info.Color;
        }

        public static bool TryGetDefinition(string iconId, out SetiIconInfo info)
        {
            EnsureInitialized();
            return definitions.TryGetValue(iconId ?? "", out info);
        }

        private static string ResolveLanguageId(string fnLow)
        {
            if (string.IsNullOrEmpty(fnLow)) return null;
            string lid;
            if (fileNameToLanguageId.TryGetValue(fnLow, out lid)) return lid;
            if (fnLow.StartsWith("dockerfile.", StringComparison.Ordinal) || fnLow.StartsWith("containerfile.", StringComparison.Ordinal)) return "dockerfile";
            if (fnLow.StartsWith(".env.", StringComparison.Ordinal)) return "dotenv";
            if (fnLow == "compose.yml" || fnLow == "compose.yaml" || fnLow.StartsWith("compose.", StringComparison.Ordinal) && (fnLow.EndsWith(".yml", StringComparison.Ordinal) || fnLow.EndsWith(".yaml", StringComparison.Ordinal))) return "dockercompose";
            if (fnLow.IndexOf("docker", StringComparison.Ordinal) >= 0 && fnLow.IndexOf("compose", StringComparison.Ordinal) >= 0 && (fnLow.EndsWith(".yml", StringComparison.Ordinal) || fnLow.EndsWith(".yaml", StringComparison.Ordinal))) return "dockercompose";
            if (fnLow.StartsWith("tsconfig.", StringComparison.Ordinal) && fnLow.EndsWith(".json", StringComparison.Ordinal)) return "jsonc";
            if (fnLow.StartsWith("jsconfig.", StringComparison.Ordinal) && fnLow.EndsWith(".json", StringComparison.Ordinal)) return "jsonc";
            if (fnLow.StartsWith("jenkinsfile", StringComparison.Ordinal)) return "groovy";
            int dot = fnLow.IndexOf('.');
            while (dot >= 0 && dot + 1 < fnLow.Length)
            {
                string ext = fnLow.Substring(dot + 1);
                if (extToLanguageId.TryGetValue(ext, out lid)) return lid;
                dot = fnLow.IndexOf('.', dot + 1);
            }
            return null;
        }

