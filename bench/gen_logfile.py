#!/usr/bin/env python3
"""Generate a large, realistic-looking application log file (deterministic for a given seed and size).

    python3 bench/gen_logfile.py /tmp/cl-bench-files/app-100MB.log --mb 100

Lines look like typical service logs (ISO timestamp, level, thread, logger, message with ids / latencies / paths,
occasional multi-line stack traces), ~140 bytes average, LF line endings, pure ASCII. The first line contains a
unique marker token (CLBENCH_<n>MB_<seed>) that the harness uses to recognise that the top of the file is painted.
"""
import argparse
import os
import random
import sys
import time

LEVELS = ["INFO"] * 70 + ["DEBUG"] * 18 + ["WARN"] * 8 + ["ERROR"] * 3 + ["TRACE"]
LOGGERS = [
    "com.acme.orders.OrderService", "com.acme.orders.OrderRepository", "com.acme.billing.InvoiceJob",
    "com.acme.http.RequestLogger", "com.acme.auth.TokenValidator", "com.acme.cache.RedisClient",
    "com.acme.search.IndexWriter", "com.acme.payments.StripeGateway", "com.acme.inventory.StockSync",
    "org.hibernate.SQL", "io.netty.channel.DefaultChannelPipeline", "com.zaxxer.hikari.pool.HikariPool",
]
PATHS = ["/api/v1/orders", "/api/v1/orders/{id}", "/api/v1/users/{id}/cart", "/api/v2/search", "/healthz",
         "/api/v1/invoices/{id}/pdf", "/api/v1/payments/intent", "/metrics", "/api/v1/inventory/sku/{id}"]
METHODS = ["GET"] * 6 + ["POST"] * 3 + ["PUT", "DELETE"]
STATUS = [200] * 40 + [201] * 5 + [204] * 3 + [304] * 2 + [400, 401, 403, 404, 404, 409, 429, 500, 502, 503]
TEMPLATES = [
    "{m} {p} status={s} latency_ms={lat} bytes={b} user=u_{u} req_id={rid}",
    "Processed order id={oid} items={n} total={amt} currency=EUR customer=c_{u} took {lat}ms",
    "Cache {hm} key=order:{oid} ttl={ttl}s size={b}B",
    "select o.id, o.status, o.total from orders o where o.customer_id=? and o.created_at>? [{lat}ms rows={n}]",
    "Token validated sub=u_{u} scope=orders:read,orders:write exp={exp} kid=k{n}",
    "Indexed {n} documents into shard-{sh} in {lat}ms (queue depth {q})",
    "Payment intent pi_{rid} amount={amt} status=requires_capture attempt={n}",
    "Stock sync sku={oid} warehouse=wh-{sh} delta={d} new_level={q}",
    "HikariPool-1 - Pool stats (total={q}, active={n}, idle={sh}, waiting=0)",
    "Retrying request to upstream inventory-svc attempt={n} backoff_ms={lat} reason=ConnectTimeout",
]
STACK = [
    "java.lang.IllegalStateException: order {oid} is already captured",
    "\tat com.acme.payments.StripeGateway.capture(StripeGateway.java:{n})",
    "\tat com.acme.orders.OrderService.complete(OrderService.java:{q})",
    "\tat com.acme.http.Router.dispatch(Router.java:88)",
    "\tat io.netty.channel.AbstractChannelHandlerContext.invokeChannelRead(AbstractChannelHandlerContext.java:379)",
]


def generate(path, megabytes, seed=1):
    target = int(megabytes * 1024 * 1024)
    rnd = random.Random(seed)
    t = time.mktime((2026, 3, 14, 8, 0, 0, 0, 0, -1))
    tmp = path + ".part"
    written = 0
    with open(tmp, "w", encoding="ascii", newline="\n") as f:
        header = "# CLBENCH_%dMB_%d synthetic service log generated by bench/gen_logfile.py\n" % (int(megabytes), seed)
        f.write(header)
        written += len(header)
        buf = []
        buf_len = 0
        while written + buf_len < target:
            t += rnd.random() * 0.02
            ms = int((t % 1) * 1000)
            ts = time.strftime("%Y-%m-%dT%H:%M:%S", time.gmtime(t)) + ".%03dZ" % ms
            level = rnd.choice(LEVELS)
            msg = rnd.choice(TEMPLATES).format(
                m=rnd.choice(METHODS), p=rnd.choice(PATHS).replace("{id}", str(rnd.randint(1000, 999999))),
                s=rnd.choice(STATUS), lat=rnd.randint(1, 2500), b=rnd.randint(80, 250000), u=rnd.randint(1, 99999),
                rid="%016x" % rnd.getrandbits(64), oid=rnd.randint(100000, 9999999), n=rnd.randint(1, 64),
                amt="%.2f" % (rnd.random() * 900), hm=rnd.choice(["hit", "hit", "hit", "miss"]),
                ttl=rnd.choice([60, 300, 3600]), exp=1773000000 + rnd.randint(0, 99999), sh=rnd.randint(0, 15),
                q=rnd.randint(0, 500), d=rnd.randint(-20, 20))
            line = "%s %-5s [worker-%02d] %s - %s\n" % (ts, level, rnd.randint(1, 32), rnd.choice(LOGGERS), msg)
            if level == "ERROR" and rnd.random() < 0.5:
                line += "\n".join(s.format(oid=rnd.randint(100000, 9999999), n=rnd.randint(40, 400),
                                           q=rnd.randint(40, 900)) for s in STACK) + "\n"
            buf.append(line)
            buf_len += len(line)
            if buf_len > (1 << 20):
                f.write("".join(buf))
                written += buf_len
                buf, buf_len = [], 0
        rest = "".join(buf)[: max(0, target - written)]
        if rest:
            rest = rest[: rest.rfind("\n") + 1] if "\n" in rest else ""
            f.write(rest)
    os.replace(tmp, path)
    return os.path.getsize(path)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("path")
    ap.add_argument("--mb", type=float, default=100)
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()
    d = os.path.dirname(os.path.abspath(a.path))
    os.makedirs(d, exist_ok=True)
    t0 = time.time()
    size = generate(a.path, a.mb, a.seed)
    sys.stderr.write("wrote %s (%d bytes) in %.1fs\n" % (a.path, size, time.time() - t0))


if __name__ == "__main__":
    main()
